/**
 * Generates the Quran's structure under `src/lib/quran/`:
 *
 *   surahs.ts    — the 114 names and ayah counts the recitation log's
 *                  من ← إلى picker needs.
 *   structure.ts — where each of the 30 أجزاء and 604 pages begins, which is
 *                  what turns a recorded range into "٧ أجزاء و١٢ صفحة" and
 *                  into the juz map on a student's page.
 *
 * WHY A GENERATOR AND NOT A TYPED-OUT LIST:
 *
 * Surah names are Quranic orthography. Typing them by hand is how a ـهِ loses
 * its kasra and a ٱ becomes an ا, and nobody notices until a معلمة does. The
 * names here are fetched verbatim from a published Uthmani edition and written
 * out unchanged apart from dropping the leading "سُورَةُ " word, which the UI
 * supplies itself.
 *
 * The ayah counts are the same fetch, so the picker can never offer آية ١٢٠
 * of a surah that has ١١٠ — a bound the UI would otherwise have to guess.
 *
 * Run it when the file needs rebuilding; it is not part of the build:
 *
 *     node scripts/generate-quran-metadata.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DIR = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "lib",
  "quran",
);
const OUT = path.join(DIR, "surahs.ts");
const OUT_STRUCTURE = path.join(DIR, "structure.ts");

const SOURCE = "https://api.alquran.cloud/v1/surah";
const META_SOURCE = "https://api.alquran.cloud/v1/meta";

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`${SOURCE} returned ${response.status}`);
}
const payload = await response.json();
const surahs = payload.data;

if (!Array.isArray(surahs) || surahs.length !== 114) {
  throw new Error(`expected 114 surahs, got ${surahs?.length}`);
}

// Sanity checks against facts that are not in the payload, so a silently
// changed upstream shape fails here rather than in front of a معلمة.
const EXPECTED = { 1: 7, 2: 286, 18: 110, 114: 6 };
for (const [number, ayahs] of Object.entries(EXPECTED)) {
  const surah = surahs[Number(number) - 1];
  if (surah.number !== Number(number) || surah.numberOfAyahs !== ayahs) {
    throw new Error(
      `surah ${number}: expected ${ayahs} ayahs, got ${surah.numberOfAyahs}`,
    );
  }
}

/**
 * Every Arabic combining mark, including the Quranic ones the app's name
 * search does not know about (U+0610–061A, U+06D6–06ED and the alif wasla).
 *
 * Used ONLY to build a search key. The displayed name is never touched — a
 * معلمة types "الكهف" and must find ٱلْكَهۡفِ, but what she then sees on screen
 * is the edition's own spelling, mark for mark.
 */
const MARKS = /[ؐ-ًؚ-ٰٟۖ-ۭـ]/gu;

function searchKey(name) {
  return name
    .replace(MARKS, "")
    .replace(/[آأإٱ]/gu, "ا")
    .replace(/ى/gu, "ي")
    .replace(/ة/gu, "ه");
}

const rows = surahs.map((surah) => {
  // "سُورَةُ ٱلْفَاتِحَةِ" -> "ٱلْفَاتِحَةِ". The UI writes the word سورة itself
  // when it needs it, and repeating it in every option makes a dropdown of 114
  // rows read as one long column of the same word.
  const name = surah.name.replace(/^سُورَةُ\s*/u, "");
  return (
    `  { number: ${surah.number}, name: "${name}", plain: "${searchKey(name)}", ` +
    `englishName: "${surah.englishName}", ayahs: ${surah.numberOfAyahs} },`
  );
});

const file = `// GENERATED by scripts/generate-quran-metadata.mjs — do not edit by hand.
//
// Names are verbatim from a published Uthmani edition; see the generator for
// why they are not typed out here. Source: ${SOURCE}

export type Surah = {
  number: number;
  /** Uthmani orthography, without the leading word سورة. Display only. */
  name: string;
  /**
   * The same name with every mark stripped, so typing "الكهف" finds ٱلْكَهۡفِ.
   * A search key — never shown, never a substitute for \`name\`.
   */
  plain: string;
  englishName: string;
  /** Upper bound for an ayah number in this surah. */
  ayahs: number;
};

export const SURAHS: readonly Surah[] = [
${rows.join("\n")}
];

/** Total ayahs in the Quran — the denominator for "how much of it". */
export const TOTAL_AYAHS = SURAHS.reduce((sum, surah) => sum + surah.ayahs, 0);

export function surahByNumber(number: number): Surah | undefined {
  return SURAHS[number - 1];
}
`;

fs.mkdirSync(DIR, { recursive: true });
fs.writeFileSync(OUT, file, "utf8");
console.log(
  `wrote ${path.relative(process.cwd(), OUT)} — 114 surahs, ` +
    `${surahs.reduce((sum, s) => sum + s.numberOfAyahs, 0)} ayahs`,
);

// =============================================================================
// structure.ts — where the أجزاء and the pages begin
// =============================================================================

const metaResponse = await fetch(META_SOURCE);
if (!metaResponse.ok) {
  throw new Error(`${META_SOURCE} returned ${metaResponse.status}`);
}
const meta = (await metaResponse.json()).data;

const juzStarts = meta.juzs.references;
const pageStarts = meta.pages.references;

// Again, checks against known facts rather than trust: 30 أجزاء, 604 pages in
// the King Fahd layout, جزء ١ opens at الفاتحة ١ and جزء ٢ at البقرة ١٤٢.
if (juzStarts.length !== 30) throw new Error(`expected 30 juz, got ${juzStarts.length}`);
if (pageStarts.length !== 604) throw new Error(`expected 604 pages, got ${pageStarts.length}`);
if (juzStarts[0].surah !== 1 || juzStarts[0].ayah !== 1) {
  throw new Error("juz 1 does not begin at al-Fatiha 1");
}
if (juzStarts[1].surah !== 2 || juzStarts[1].ayah !== 142) {
  throw new Error("juz 2 does not begin at al-Baqara 142");
}
if (meta.ayahs.count !== 6236) {
  throw new Error(`expected 6236 ayahs, got ${meta.ayahs.count}`);
}

const pairs = (refs, perLine) => {
  const items = refs.map((r) => `[${r.surah}, ${r.ayah}]`);
  const lines = [];
  for (let i = 0; i < items.length; i += perLine) {
    lines.push("  " + items.slice(i, i + perLine).join(", ") + ",");
  }
  return lines.join("\n");
};

const structure = `// GENERATED by scripts/generate-quran-metadata.mjs — do not edit by hand.
//
// Where each جزء and each mushaf page begins, as [surah, ayah]. Source:
// ${META_SOURCE}
//
// The page numbers are the King Fahd Complex layout — 604 pages — which is
// the mushaf the academy's students actually hold, and the one every "صفحة
// ٢٩٣" in the app refers to.

/** A boundary: the first ayah of a جزء or a page. */
export type StartRef = readonly [surah: number, ayah: number];

/** JUZ_STARTS[n - 1] is where جزء n begins. */
export const JUZ_STARTS: readonly StartRef[] = [
${pairs(juzStarts, 5)}
];

/** PAGE_STARTS[n - 1] is where page n begins. */
export const PAGE_STARTS: readonly StartRef[] = [
${pairs(pageStarts, 6)}
];

export const JUZ_COUNT = JUZ_STARTS.length;
export const PAGE_COUNT = PAGE_STARTS.length;
`;

fs.writeFileSync(OUT_STRUCTURE, structure, "utf8");
console.log(
  `wrote ${path.relative(process.cwd(), OUT_STRUCTURE)} — ` +
    `${juzStarts.length} juz, ${pageStarts.length} pages`,
);
